-- ============================================================================
--  VISTA
--  "cliente" y "apellido" provienen de la tabla cliente (el comprador).
-- ============================================================================

CREATE OR REPLACE VIEW historial_compras AS
SELECT
    v.id_venta,
    v.fecha_emision,
    td.nombre AS tipo_documento,
    cl.nombre AS cliente,
    cl.apellido,
    pr.nombre AS producto,
    dv.cantidad,
    dv.precio_unitario,
    dv.subtotal,
    mp.descripcion AS medio_pago,
    pe.nombre AS persona
FROM venta v
INNER JOIN cliente cl        ON v.id_cliente = cl.id_cliente
INNER JOIN persona pe        ON v.id_persona = pe.id_persona
INNER JOIN tipo_documento td ON v.id_tipo_documento = td.id_documento
INNER JOIN medio_pago mp     ON v.id_medio_pago = mp.id_medio_pago
INNER JOIN detalle_venta dv  ON v.id_venta = dv.id_venta
INNER JOIN producto pr       ON dv.id_producto = pr.id_producto;


SET NAMES utf8mb4;
SET FOREIGN_KEY_CHECKS = 0;

-- 1. Crear la base de datos (no se borra si ya existe)
CREATE DATABASE IF NOT EXISTS proyecto
    CHARACTER SET utf8mb4
    COLLATE utf8mb4_unicode_ci;

USE proyecto;

-- 2. Limpieza previa (MySQL no admite "CASCADE" en DROP TABLE ni multiples tablas)
DROP VIEW  IF EXISTS historial_compras;
DROP TABLE IF EXISTS movimiento_caja;
DROP TABLE IF EXISTS detalle_venta;
DROP TABLE IF EXISTS venta;
DROP TABLE IF EXISTS usuario;
DROP TABLE IF EXISTS persona;
DROP TABLE IF EXISTS cliente;
DROP TABLE IF EXISTS rol;
DROP TABLE IF EXISTS producto;
DROP TABLE IF EXISTS tienda;
DROP TABLE IF EXISTS medio_pago;
DROP TABLE IF EXISTS tipo_documento;
DROP TABLE IF EXISTS parametro;
DROP TABLE IF EXISTS correlativo;

-- ============================================================================
--  ESTRUCTURA
-- ============================================================================

-- Parametros del sistema (IGV, RUC emisor, etc). Editables sin tocar el codigo.
CREATE TABLE parametro (
    id_parametro VARCHAR(30)  NOT NULL,
    valor        VARCHAR(50)  NOT NULL,
    descripcion  VARCHAR(100) NOT NULL,
    PRIMARY KEY (id_parametro)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE tipo_documento (
    id_documento VARCHAR(25)  NOT NULL,
    nombre      VARCHAR(50)  NOT NULL,
    PRIMARY KEY (id_documento)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE medio_pago (
    id_medio_pago VARCHAR(10)  NOT NULL,
    descripcion   VARCHAR(100) NOT NULL,
    PRIMARY KEY (id_medio_pago)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Cada tienda es administrada por uno o mas usuarios (tabla usuario.id_tienda).
-- slug: minusculas y guiones, unico (lo valida la aplicacion antes de insertar).
-- Los datos fiscales y las series (razon_social, ruc, direccion_fiscal,
-- telefono, serie_boleta, serie_factura) son opcionales: si estan vacios los
-- comprobantes usan los parametros globales del emisor (tabla parametro).
-- serie_boleta y serie_factura son las que numera el punto de venta y la
-- emision electronica (tabla correlativo).
CREATE TABLE tienda (
    id_tienda        INT          NOT NULL AUTO_INCREMENT,
    nombre           VARCHAR(100) NOT NULL,
    rubro            VARCHAR(80)  NOT NULL,
    slug             VARCHAR(80)  NOT NULL,
    color_primario   VARCHAR(7)   NOT NULL DEFAULT '#0071e3',
    color_secundario VARCHAR(7)   NOT NULL DEFAULT '#1d1d1f',
    logo_url         VARCHAR(255),
    razon_social     VARCHAR(150),
    ruc              VARCHAR(11),
    direccion_fiscal VARCHAR(200),
    telefono         VARCHAR(30),
    serie_boleta     VARCHAR(4),
    serie_factura    VARCHAR(4),
    PRIMARY KEY (id_tienda),
    UNIQUE KEY uk_tienda_slug (slug)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- uk_persona_correo: la aplicacion vincula cliente y persona por correo
-- (Login.esClienteRegistrado y FacturaDAO resuelven la compra con esa misma
--  relacion), por lo que el correo debe ser unico.
CREATE TABLE persona (
    id_persona       VARCHAR(25) NOT NULL,
    nombre           VARCHAR(50) NOT NULL,
    apellido         VARCHAR(50) NOT NULL,
    fecha_nacimiento DATE,
    correo           VARCHAR(100),
    telefono         VARCHAR(9),
    usuario          VARCHAR(50),
    PRIMARY KEY (id_persona),
    UNIQUE KEY uk_persona_correo (correo)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Catalogo de roles. La tabla "rol" es la unica fuente de verdad de los
-- permisos: ADMIN para el panel de administracion, VENDEDOR para el POS y
-- CLIENTE para el comprador.
CREATE TABLE rol (
    id_rol      VARCHAR(15)  NOT NULL,
    nombre      VARCHAR(50)  NOT NULL,
    descripcion VARCHAR(100) NOT NULL,
    PRIMARY KEY (id_rol)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- id_usuario: GENERATED BY DEFAULT AS IDENTITY (Postgres) -> AUTO_INCREMENT (MySQL)
-- uk_usuario_usuario: el login busca por este campo, debe ser unico.
-- contrasena: SHA-256 (carga inicial) o BCrypt (desde que la app crea/actualiza
-- el hash); nunca texto plano.
-- id_rol: una sola FK, el rol vive en la base y no se deduce en el codigo.
-- Esta tabla es SOLO para cuentas del panel (ADMIN, VENDEDOR, SUPER_ADMIN).
-- El comprador tiene su propia ficha en la tabla cliente y no se registra aqui:
-- una fila de comprador en "usuario" lo haria aparecer como personal.
-- estado: ACTIVO o SUSPENDIDO; el SUPER_ADMIN lo controla desde su consola.
CREATE TABLE usuario (
    id_usuario INT          NOT NULL AUTO_INCREMENT,
    usuario    VARCHAR(50)  NOT NULL,
    contrasena VARCHAR(255) NOT NULL,
    id_persona VARCHAR(25)  NOT NULL,
    id_rol     VARCHAR(15)  NOT NULL DEFAULT 'ADMIN',
    estado     VARCHAR(15)  NOT NULL DEFAULT 'ACTIVO',
    id_tienda  INT          NOT NULL,
    PRIMARY KEY (id_usuario),
    UNIQUE KEY uk_usuario_usuario (usuario),
    KEY idx_usuario_id_persona (id_persona),
    KEY idx_usuario_id_rol (id_rol),
    KEY idx_usuario_id_tienda (id_tienda),
    CONSTRAINT fk_usuario_persona FOREIGN KEY (id_persona)
        REFERENCES persona (id_persona),
    CONSTRAINT fk_usuario_rol FOREIGN KEY (id_rol)
        REFERENCES rol (id_rol),
    CONSTRAINT fk_usuario_tienda FOREIGN KEY (id_tienda)
        REFERENCES tienda (id_tienda)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- El COMPRADOR. Tabla independiente de persona: el mismo nombre puede estar
-- en ambas sin ser la misma persona.
-- id_rol: el comprador siempre entra como CLIENTE; queda en la base para que
-- el backend no tenga que deducirlo.
CREATE TABLE cliente (
    id_cliente VARCHAR(20)  NOT NULL,
    nombre     VARCHAR(50)  NOT NULL,
    apellido   VARCHAR(50)  NOT NULL,
    telefono   VARCHAR(15),
    contrasena VARCHAR(255) NOT NULL,
    correo     VARCHAR(100),
    -- Fichas creadas desde el POS: documento fiscal (catalogo 01 SUNAT:
    -- 1 DNI, 6 RUC), direccion y tienda que las registro. Las cuentas del
    -- portal dejan estas columnas en NULL y no aparecen en la busqueda.
    tipo_documento   VARCHAR(1),
    numero_documento VARCHAR(15),
    direccion        VARCHAR(200),
    id_tienda        INT,
    id_rol     VARCHAR(15)  NOT NULL DEFAULT 'CLIENTE',
    UNIQUE KEY uk_cliente_correo (correo),
    PRIMARY KEY (id_cliente),
    KEY idx_cliente_id_rol (id_rol),
    KEY idx_cliente_documento (numero_documento, id_tienda),
    CONSTRAINT fk_cliente_rol FOREIGN KEY (id_rol)
        REFERENCES rol (id_rol)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Catalogo de productos.
--   codigo         : codigo del item en el catalogo del emisor (se envia al CDR)
--   unidad_medida  : unidad del catalogo 03 de SUNAT (NIU, UN, KG...)
--   afectacion_igv : catalogo 07 de SUNAT (01 gravada, 02 inafecta, 03 exonerada,
--                    04 gratuita). El precio del catalogo SIEMPRE incluye IGV.
--   id_tienda      : el producto pertenece a una sola tienda; un ADMIN solo
--                    gestiona (POST/PUT/DELETE) los productos de SU propia tienda.
CREATE TABLE producto (
    id_producto    INT           NOT NULL,
    nombre         VARCHAR(100)  NOT NULL,
    stock          INT           NOT NULL,
    precio         DECIMAL(10, 2) NOT NULL,
    categoria      VARCHAR(80)   NOT NULL,
    codigo         VARCHAR(50)   NOT NULL DEFAULT '',
    unidad_medida  VARCHAR(5)    NOT NULL DEFAULT 'NIU',
    afectacion_igv VARCHAR(2)    NOT NULL DEFAULT '01',
    atributos      JSON          NULL,
    id_tienda      INT           NOT NULL,
    PRIMARY KEY (id_producto),
    KEY idx_producto_id_tienda (id_tienda),
    CONSTRAINT fk_producto_tienda FOREIGN KEY (id_tienda)
        REFERENCES tienda (id_tienda)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- id_cliente = comprador  |  id_persona = persona dueña de la cuenta
-- Cabecera del comprobante de pago electronico. Los datos del receptor y los
-- totales se guardan "congelados": el comprobante emitido debe seguir
-- mostrando lo que facturo aunque el cliente o el catalogo cambien.
CREATE TABLE venta (
    id_venta          VARCHAR(36) NOT NULL,
    id_cliente        VARCHAR(20) NOT NULL,
    id_persona        VARCHAR(25) NOT NULL,
    id_tipo_documento VARCHAR(25) NOT NULL,
    numero_documento  VARCHAR(36) NOT NULL,
    id_medio_pago     VARCHAR(10) NOT NULL,
    fecha_emision     TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    serie             VARCHAR(4)   NOT NULL DEFAULT '',
    correlativo       INT          NOT NULL DEFAULT 0,
    moneda            VARCHAR(3)   NOT NULL DEFAULT 'PEN',
    condicion_operacion VARCHAR(2) NOT NULL DEFAULT '01',
    forma_pago        VARCHAR(2)   NOT NULL DEFAULT '01',
    total_venta            DECIMAL(12,2) NOT NULL DEFAULT 0.00,
    total_gravada          DECIMAL(12,2) NOT NULL DEFAULT 0.00,
    total_inafecta         DECIMAL(12,2) NOT NULL DEFAULT 0.00,
    total_exonerada        DECIMAL(12,2) NOT NULL DEFAULT 0.00,
    total_gratuita         DECIMAL(12,2) NOT NULL DEFAULT 0.00,
    total_igv              DECIMAL(12,2) NOT NULL DEFAULT 0.00,
    total_descuentos       DECIMAL(12,2) NOT NULL DEFAULT 0.00,
    monto_total_credito    DECIMAL(12,2) NOT NULL DEFAULT 0.00,
    receptor_tipo_documento VARCHAR(1)   NOT NULL DEFAULT '',
    receptor_num_documento  VARCHAR(15)  NOT NULL DEFAULT '',
    receptor_razon_social   VARCHAR(200) NOT NULL DEFAULT '',
    receptor_direccion      VARCHAR(200) NOT NULL DEFAULT '',
    receptor_ubigeo         VARCHAR(6)   NOT NULL DEFAULT '',
    receptor_distrito       VARCHAR(80)  NOT NULL DEFAULT '',
    receptor_provincia      VARCHAR(80)  NOT NULL DEFAULT '',
    receptor_departamento   VARCHAR(80)  NOT NULL DEFAULT '',
    receptor_pais           VARCHAR(2)   NOT NULL DEFAULT 'PE',
    entrega_direccion       VARCHAR(200) NOT NULL DEFAULT '',
    entrega_ubigeo          VARCHAR(6)   NOT NULL DEFAULT '',
    email_contacto          VARCHAR(100) NOT NULL DEFAULT '',
    hash_comprobante        VARCHAR(64)  NULL,
    codigo_qr               VARCHAR(500) NULL,
    xml_name                VARCHAR(120) NULL,
    estado                  VARCHAR(20)  NOT NULL DEFAULT 'EMITIDO',
    estado_sunat            VARCHAR(20)  NULL,
    cdR_summary             VARCHAR(500) NULL,
    leyendas                TEXT         NULL,
    observacion             VARCHAR(500) NOT NULL DEFAULT '',
    vendedor_usuario        VARCHAR(50)  NULL,
    vendedor_nombre         VARCHAR(150) NULL,
    PRIMARY KEY (id_venta),
    UNIQUE KEY uk_venta_serie_correlativo (serie, correlativo),
    KEY idx_venta_id_cliente (id_cliente),
    KEY idx_venta_id_persona (id_persona),
    KEY idx_venta_id_tipo_documento (id_tipo_documento),
    KEY idx_venta_id_medio_pago (id_medio_pago),
    KEY idx_venta_fecha_emision (fecha_emision),
    CONSTRAINT fk_venta_cliente FOREIGN KEY (id_cliente)
        REFERENCES cliente (id_cliente),
    CONSTRAINT fk_venta_persona FOREIGN KEY (id_persona)
        REFERENCES persona (id_persona),
    CONSTRAINT fk_venta_tipo_documento FOREIGN KEY (id_tipo_documento)
        REFERENCES tipo_documento (id_documento),
    CONSTRAINT fk_venta_medio_pago FOREIGN KEY (id_medio_pago)
        REFERENCES medio_pago (id_medio_pago)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- id_detalle: GENERATED BY DEFAULT AS IDENTITY (Postgres) -> AUTO_INCREMENT (MySQL)
-- Items del comprobante.
--   precio_unitario : precio de venta unitario CON IGV (catalogo del producto)
--   valor_unitario  : valor unitario SIN IGV (base imponible del item)
--   subtotal        : monto total del item (base + IGV del item)
CREATE TABLE detalle_venta (
    id_detalle      INT           NOT NULL AUTO_INCREMENT,
    id_venta        VARCHAR(36)   NOT NULL,
    id_producto     INT           NOT NULL,
    cantidad        INT           NOT NULL,
    precio_unitario DECIMAL(12, 2) NOT NULL,
    subtotal        DECIMAL(12, 2) NOT NULL,
    valor_unitario  DECIMAL(12, 6) NOT NULL DEFAULT 0.000000,
    igv_item        DECIMAL(12, 2) NOT NULL DEFAULT 0.00,
    descuento       DECIMAL(12, 2) NOT NULL DEFAULT 0.00,
    codigo_item     VARCHAR(50)   NOT NULL DEFAULT '',
    descripcion     VARCHAR(500)  NOT NULL DEFAULT '',
    unidad_medida   VARCHAR(5)    NOT NULL DEFAULT 'NIU',
    afectacion_igv  VARCHAR(2)    NOT NULL DEFAULT '01',
    PRIMARY KEY (id_detalle),
    KEY idx_detalle_id_venta (id_venta),
    KEY idx_detalle_id_producto (id_producto),
    CONSTRAINT fk_detalle_venta FOREIGN KEY (id_venta)
        REFERENCES venta (id_venta),
    CONSTRAINT fk_detalle_producto FOREIGN KEY (id_producto)
        REFERENCES producto (id_producto)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Numeracion correlativa por serie (SUNAT exige series correlativas, sin
-- saltos ni duplicados). El numero NO se puede calcular con COUNT(): dos
-- ventas simultaneas lo repetirian. Se bloquea la fila con SELECT ... FOR
-- UPDATE dentro de la misma transaccion que guarda la venta.
CREATE TABLE correlativo (
    serie             VARCHAR(4)  NOT NULL,
    id_tipo_documento VARCHAR(25) NOT NULL,
    ultimo_numero     INT         NOT NULL DEFAULT 0,
    PRIMARY KEY (serie)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Turnos de caja del POS: fondo inicial, cierre y arqueo fisico. Guarda el
-- usuario como snapshot (sin FK) para que el historico sobreviva a la baja de
-- una cuenta. El resumen por metodo de pago se calcula de las ventas del
-- rango [fecha_apertura, fecha_cierre], no se duplica aqui.
CREATE TABLE movimiento_caja (
    id_caja          VARCHAR(36)    NOT NULL,
    id_tienda        INT            NOT NULL,
    usuario          VARCHAR(50)    NOT NULL,
    nombre_vendedor  VARCHAR(120)   NOT NULL DEFAULT '',
    estado           VARCHAR(12)    NOT NULL DEFAULT 'ABIERTA',
    monto_apertura   DECIMAL(12, 2) NOT NULL DEFAULT 0.00,
    fecha_apertura   TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    monto_sistema    DECIMAL(12, 2) NULL,
    efectivo_contado DECIMAL(12, 2) NULL,
    diferencia       DECIMAL(12, 2) NULL,
    observacion      VARCHAR(200)   NOT NULL DEFAULT '',
    fecha_cierre     TIMESTAMP      NULL,
    PRIMARY KEY (id_caja),
    KEY idx_caja_turno (id_tienda, usuario, estado),
    KEY idx_caja_fecha_apertura (fecha_apertura)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;


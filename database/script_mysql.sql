-- ============================================================================
--  SISTEMA DE FACTURACION - Script unificado de base de datos
--  Motor: MySQL 8.0 / MariaDB 10.5+  |  Charset: utf8mb4  |  InnoDB
--
--  Base de datos : proyecto
--  Servidor      : localhost:3306
--  Driver        : lib/mysql-connector-j-8.4.0.jar
--  Conexion      : Config.ConexionMySQL
--
--  Uso: pegar y ejecutar completo en MySQL Workbench / phpMyAdmin / DBeaver,
--  o desde la terminal:
--     mysql -u root -p < database/script_mysql.sql
--
--  Modelo de venta:
--    venta.id_cliente -> COMPRADOR  (tabla cliente)
--    venta.id_persona -> PERSONA    (tabla persona, dueña de la cuenta)
--    El total de una venta no se almacena: se obtiene sumando
--    detalle_venta.subtotal.
